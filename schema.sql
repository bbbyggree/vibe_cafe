-- ========================================================
-- 바이브 카페 (Vibe Cafe) - 주문 내역 테이블 생성 및 권한 설정
-- ========================================================

-- 1. orders 테이블 생성
CREATE TABLE IF NOT EXISTS orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 주문 고유 번호
    customer_name VARCHAR(50) NOT NULL,                           -- 고객 이름 (필수)
    customer_phone VARCHAR(20),                                   -- 전화번호
    drink VARCHAR(50) NOT NULL,                                   -- 음료/메뉴 이름 (필수)
    size VARCHAR(10) NOT NULL DEFAULT 'M',                        -- 사이즈 (S, M, L)
    options TEXT,                                                 -- 추가 옵션들 (예: '샷 추가, 크림 추가')
    quantity INT NOT NULL DEFAULT 1,                              -- 수량
    requests TEXT,                                                -- 요청사항
    total_price INT NOT NULL,                                     -- 총 결제 금액
    status VARCHAR(20) DEFAULT 'PENDING',                         -- 주문 상태 ('PENDING', 'COMPLETED' 등)
    created_at TIMESTAMPTZ DEFAULT NOW()                          -- 주문 일시
);

-- 2. 프론트엔드(웹 브라우저)에서 데이터 삽입 및 조회가 가능하도록 RLS(Row Level Security) 설정
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

-- 익명 사용자(anon) 및 인증 사용자(authenticated) 모두 주문 등록(INSERT) 가능하도록 허용
DROP POLICY IF EXISTS "주문 등록 허용" ON orders;
CREATE POLICY "주문 등록 허용" 
ON orders FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- 주문 내역 조회(SELECT) 허용
DROP POLICY IF EXISTS "주문 조회 허용" ON orders;
CREATE POLICY "주문 조회 허용" 
ON orders FOR SELECT 
TO anon, authenticated 
USING (true);

